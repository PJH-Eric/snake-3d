import { chromium } from 'playwright-core';
const out = (process.env.SHOT_DIR || '.shots') + '/';
const b = await chromium.launch({ channel: 'msedge', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await b.newContext({ viewport: { width: 1280, height: 800 } });
const p = await ctx.newPage();
const errs = [];
p.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.type() + ': ' + m.text()); });
p.on('pageerror', e => errs.push('pageerror: ' + e.message));
await p.goto('http://localhost:4173/');
await p.waitForTimeout(800);
await p.screenshot({ path: out + 'home.png' });
await p.getByRole('button', { name: '單人挑戰' }).click();
await p.waitForTimeout(500);
await p.screenshot({ path: out + 'challenge.png' });
await p.getByRole('button', { name: '開始遊戲' }).first().click();
await p.waitForTimeout(4500);
await p.screenshot({ path: out + 'game.png' });
console.log(errs.join('\n') || 'no errors');
await b.close();
